// Builds a static copy of the site into dist/ for upload to Hostinger (or any Apache/LiteSpeed host).
// app/api is moved aside during the build because POST route handlers cannot be statically exported;
// deploy/contact.php takes its place: it emails info@originsoftwares.com and saves the lead to the originsoftwares.com dashboard.
import { execSync } from 'node:child_process'
import { cpSync, existsSync, readdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// DASHBOARD_LEADS_URL / DASHBOARD_LEADS_TOKEN (and any NEXT_PUBLIC_* overrides) live in .env.local, kept out of git.
for (const file of ['.env.local', '.env']) if (existsSync(file)) process.loadEnvFile(file)

const api = 'app/api'
const parked = '.api-parked'
if (existsSync(parked)) throw new Error(`${parked} exists from an interrupted build; move it back to ${api} first.`)

// A fresh build: OneDrive turns files of a previous .next into placeholders that make next build fail (EINVAL readlink).
for (const dir of ['.next', 'out']) rmSync(dir, { recursive: true, force: true })
renameSync(api, parked)
try {
  // The form posts to /api/contact, which .htaccess maps to the PHP mailer copied in below.
  execSync('next build', { stdio: 'inherit', env: { ...process.env, STATIC_EXPORT: '1', NEXT_PUBLIC_ENABLE_CONTACT_FORM: 'true', NEXT_PUBLIC_API_BASE_URL: '/api' } })
} finally {
  renameSync(parked, api)
}

rmSync('dist', { recursive: true, force: true })
cpSync('out', 'dist', { recursive: true })
// The export names OG images opengraph-image-<hash>, but the pages link to .../opengraph-image (a rewrite on a Next server).
for (const entry of readdirSync('dist', { recursive: true })) {
  if (!entry.startsWith('_next') && /(^|[\\/])opengraph-image-\w+$/.test(entry)) {
    renameSync(join('dist', entry), join('dist', entry.replace(/opengraph-image-\w+$/, 'opengraph-image')))
  }
}
cpSync('deploy/contact.php', 'dist/api/contact.php')
const { DASHBOARD_LEADS_URL: url = '', DASHBOARD_LEADS_TOKEN: token = '' } = process.env
const php = value => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
writeFileSync('dist/api/contact-config.php', `<?php\n// Generated by npm run build:static from .env.local.\nreturn ['dashboard_url' => ${php(url)}, 'dashboard_token' => ${php(token)}];\n`)
if (!url || !token) console.warn('\nDASHBOARD_LEADS_URL / DASHBOARD_LEADS_TOKEN not set: enquiries will be emailed but not saved to the dashboard.')
if (!existsSync('dist/.htaccess')) cpSync('public/.htaccess', 'dist/.htaccess')
console.log('\nStatic site written to dist/. Upload its contents (including .htaccess) to public_html.')
